const LNG_MIN = 12.7492;
const LNG_MAX = 14.9922;
const LAT_MIN = 47.4611;
const LAT_MAX = 48.7726;
const LAT_MID = (LAT_MIN + LAT_MAX) / 2;
// Breitenkorrektur: ein Laengengrad ist auf 48° nur ~cos(48°) so lang wie ein Breitengrad
const LNG_SCALE = Math.cos((LAT_MID * Math.PI) / 180);

const PADDING = 28;
const INNER_WIDTH = 1000 - 2 * PADDING;
const INNER_HEIGHT = INNER_WIDTH * ((LAT_MAX - LAT_MIN) / ((LNG_MAX - LNG_MIN) * LNG_SCALE));

/** ViewBox-Masse der Karte (Breite fix 1000, Hoehe aus der echten Geografie). */
export const MAP_VIEW = {
  width: 1000,
  height: Math.round(INNER_HEIGHT + 2 * PADDING),
};

/** Kilometer in ViewBox-Einheiten (fuer Seen-Ellipsen, Massstabsbalken). */
export const UNITS_PER_KM = INNER_HEIGHT / ((LAT_MAX - LAT_MIN) * 111.32);

/** WGS84 → ViewBox-Koordinaten. */
export function projectToMap(lng: number, lat: number): { x: number; y: number } {
  return {
    x: PADDING + ((lng - LNG_MIN) / (LNG_MAX - LNG_MIN)) * INNER_WIDTH,
    y: PADDING + ((LAT_MAX - lat) / (LAT_MAX - LAT_MIN)) * INNER_HEIGHT,
  };
}

/** SVG-Pfad aus [lng,lat]-Punkten (projiziert, gerundet auf 1 Nachkommastelle). */
export function buildMapPath(points: LngLat[], close: boolean): string {
  const parts = points.map(([lng, lat], index) => {
    const { x, y } = projectToMap(lng, lat);
    return `${index === 0 ? "M" : "L"}${x.toFixed(1)} ${y.toFixed(1)}`;
  });
  return parts.join("") + (close ? "Z" : "");
}
